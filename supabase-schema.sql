create table if not exists public.cameras (
  id bigint primary key,
  name text not null,
  brand text not null default '',
  type text not null default 'Máy ảnh',
  price numeric not null default 0,
  long_rates jsonb not null default '{}'::jsonb,
  hourly_rates jsonb not null default '{}'::jsonb,
  lens text not null default '',
  desc text not null default '',
  image text not null default '',
  available boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.samples (
  id uuid primary key,
  src text not null,
  description text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.plans (
  id text primary key,
  title text not null,
  price numeric not null default 0,
  note text not null default '',
  badge text not null default '',
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.policies (
  num text primary key,
  title text not null,
  text text not null default '',
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.settings (
  id integer primary key default 1,
  name text not null default 'Tiệm Ảnh Capy',
  phone text not null default '',
  zalo text not null default '#',
  facebook text not null default '#',
  address text not null default 'Bàu Tró, Quảng Trị',
  contact_title text not null default 'Nhắn Capy để',
  contact_italic text not null default 'giữ máy.',
  contact_subtext text not null default 'Hotline / Zalo',
  qr_image text not null default '',
  hero_image text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  camera_id bigint references public.cameras(id) on delete set null,
  camera text not null default '',
  plan text not null default '1-day',
  customer jsonb not null default '{}'::jsonb,
  status text not null default 'Mới',
  created_at timestamptz not null default now()
);

