-- Availability checks are exposed as safe functions; they return no customer data.
create or replace function public.is_camera_available(
  p_camera_id bigint,
  p_date date,
  p_plan text,
  p_start_time time default '00:00',
  p_hours integer default 1
) returns boolean
language sql
security definer
set search_path = public
as $$
  select not exists (
    select 1 from public.orders o
    where o.camera_id = p_camera_id
      and o.status <> 'Hủy'
      and (o.customer->>'date')::date = p_date
      and (
        o.plan <> 'hourly' or p_plan <> 'hourly' or
        (
          (p_start_time < ((o.customer->>'startTime')::time + make_interval(mins => coalesce((o.customer->>'hours')::integer,1)*60)))
          and
          ((p_start_time + make_interval(mins => coalesce(p_hours,1)*60)) > (o.customer->>'startTime')::time)
        )
      )
  );
$$;

grant execute on function public.is_camera_available(bigint,date,text,time,integer) to anon, authenticated;

create or replace function public.get_available_camera_ids(
  p_date date,
  p_plan text,
  p_start_time time default '00:00',
  p_hours integer default 1
) returns table(id bigint)
language sql
security definer
set search_path = public
as $$
  select c.id
  from public.cameras c
  where c.available = true
    and public.is_camera_available(c.id, p_date, p_plan, p_start_time, p_hours);
$$;

grant execute on function public.get_available_camera_ids(date,text,time,integer) to anon, authenticated;
